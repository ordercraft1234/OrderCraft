import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

/**
 * Writes `src/policy/stub-source.ts`: the text of `src/policy/stub.ts` as a constant, so
 * the builder can offer the stub as a download without reading the file at run time.
 * `test/policy-stub.test.ts` fails when the two drift apart.
 *
 *   pnpm --filter @ordercraft/core stub:source
 */
const stub = fileURLToPath(new URL('../src/policy/stub.ts', import.meta.url))
const target = fileURLToPath(new URL('../src/policy/stub-source.ts', import.meta.url))

const source = readFileSync(stub, 'utf8')
if (source.includes('\r')) throw new Error('stub.ts has CRLF line endings; it ships as LF')

writeFileSync(
  target,
  `// Generated by scripts/write-stub-source.ts from stub.ts — do not edit by hand.

/** What the stub is saved as: one file per policy-file format version. */
export const POLICY_STUB_FILE_NAME = 'ordercraft-policy.v1.ts'

/** The text of \`stub.ts\`, byte for byte (FR-019). */
export const POLICY_STUB_SOURCE = ${JSON.stringify(source)}
`,
)
